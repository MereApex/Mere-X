async function runAutomation(item, { manual = false } = {}) {
  if (!item || runningAutomations.has(item.id)) return;
  if (!workspaceActionAllowed("run automations")) return;
  runningAutomations.add(item.id);
  item.lastStatus = "running";
  item.lastError = "";
  item.lastRunAt = new Date().toISOString();
  if (manual && (!item.nextRunAt || new Date(item.nextRunAt).getTime() <= Date.now())) item.nextRunAt = nextAutomationRun(item);
  saveWorkspaceState();
  if (currentLocalView === "automations") renderLocalView("automations");

  const conversation = {
    id: makeId("chat"),
    title: item.name,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    archived: false,
    projectId: appState.agents.some((agent) => agent.id === item.agentId && agent.enabled !== false) ? "" : (appState.projects.some((project) => project.id === item.projectId) ? item.projectId : ""),
    agentId: appState.agents.some((agent) => agent.id === item.agentId && agent.enabled !== false) ? item.agentId : "",
    automationId: item.id,
    autoTitled: true,
    transient: false,
    messages: [{ id: makeId("message"), role: "user", text: item.prompt, attachments: [], createdAt: new Date().toISOString() }]
  };
  const answer = { id: makeId("message"), role: "assistant", text: "", attachments: [], artifacts: [], createdAt: new Date().toISOString() };
  conversation.messages.push(answer);
  appState.conversations.unshift(conversation);
  item.lastConversationId = conversation.id;
  const startedAt = Date.now();
  let completion = null;
  const usedTools = [];

  try {
    const context = replyContext(conversation, { effort: item.mode, ...(item.tool ? { tool: item.tool } : {}) });
    if (settingValue("plugin-confirmation", true)) context.plugins = [];
    for await (const piece of streamAssistantReply({
      messages: [{ role: "user", text: item.prompt, attachments: [] }],
      context,
      onEvent: (event) => {
        if (event.type === "done") completion = event;
        if (event.type === "tool" && event.tool) usedTools.push(event.tool);
        if (event.type === "artifact") {
          const [artifact] = normalizeGeneratedArtifacts([event.artifact]);
          if (artifact && !answer.artifacts.some((item) => item.url === artifact.url)) answer.artifacts.push(artifact);
        }
      }
    })) answer.text += piece;
    if (!answer.text.trim() && !answer.artifacts.length) throw new AssistantError("The automation returned an empty response.");
    answer.model = completion?.model || `Mere X ${item.mode}`;
    answer.usage = completion?.usage || null;
    conversation.lastMode = item.mode;
    conversation.lastTool = context.tool;
    item.lastStatus = "completed";
    item.runCount = Number(item.runCount || 0) + 1;
    conversation.updatedAt = new Date().toISOString();
    recordActivity("assistant_completed", { conversationId: conversation.id, title: conversation.title, agentId: conversation.agentId || "", mode: context.effort, tool: context.tool, tools: [...new Set(usedTools)], usage: completion?.usage || null, durationMs: Date.now() - startedAt, automationId: item.id });
    recordActivity("automation_completed", { automationId: item.id, conversationId: conversation.id, name: item.name, durationMs: Date.now() - startedAt });
    pushNotification("Automation completed", `${item.name} · result saved in conversations`, { type: "automation_completed", conversationId: conversation.id, automationId: item.id });
    maybeIssueUsageAlerts();
  } catch (error) {
    const detail = error instanceof AssistantError ? error.message : "Mere X could not complete this automation.";
    answer.text = `Automation failed: ${detail}`;
    item.lastStatus = "failed";
    item.lastError = detail;
    recordActivity("automation_failed", { automationId: item.id, conversationId: conversation.id, name: item.name, error: detail, durationMs: Date.now() - startedAt });
    pushNotification("Automation failed", `${item.name} · ${detail}`, { type: "automation_failed", conversationId: conversation.id, automationId: item.id });
  } finally {
    runningAutomations.delete(item.id);
    item.nextRunAt = nextAutomationRun(item);
    item.updatedAt = new Date().toISOString();
    saveWorkspaceState();
    renderRecents();
    if (currentLocalView === "automations") renderLocalView("automations");
  }
}

function checkAutomations() {
  const now = Date.now();
  for (const item of appState.automations) {
    if (!item.enabled || runningAutomations.has(item.id)) continue;
    if (!item.nextRunAt) item.nextRunAt = nextAutomationRun(item, now);
    if (new Date(item.nextRunAt).getTime() <= now) {
      item.nextRunAt = nextAutomationRun(item, now);
      saveWorkspaceState();
      runAutomation(item);
    }
  }
  maybeGenerateDigests();
}

