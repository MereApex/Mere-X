function fileIsReferenced(fileId, exceptAgentId = "") {
  return appState.projects.some((project) => (project.files || []).some((file) => file.id === fileId))
    || appState.agents.some((agent) => agent.id !== exceptAgentId && (agent.files || []).some((file) => file.id === fileId))
    || appState.conversations.some((chat) => (chat.messages || []).some((message) => (message.attachments || []).some((file) => file.id === fileId)));
}

async function removeAgentFile(agent, fileId) {
  const file = (agent?.files || []).find((item) => item.id === fileId);
  if (!agent || !file) return;
  agent.files = agent.files.filter((item) => item.id !== fileId);
  touchAgent(agent);
  const orphaned = file.remote === true && !fileIsReferenced(fileId, agent.id);
  if (orphaned) appState.files = appState.files.filter((item) => item.id !== fileId);
  saveWorkspaceState();
  renderLocalView("agents");
  if (orphaned) await apiJson(`/api/files/${encodeURIComponent(fileId)}`, { method: "DELETE" }).catch((error) => showToast(error.message));
}

async function deleteAgentRecord(agentId) {
  const agent = appState.agents.find((item) => item.id === agentId);
  if (!agent) return;
  appState.conversations.filter((item) => item.agentId === agentId).forEach((chat) => stopReply(chat.id));
  appState.agents = appState.agents.filter((item) => item.id !== agentId);
  appState.conversations = appState.conversations.filter((item) => item.agentId !== agentId);
  appState.automations.forEach((item) => { if (item.agentId === agentId) item.agentId = ""; });
  const orphaned = (agent.files || []).filter((file) => file.remote === true && !fileIsReferenced(file.id, agentId));
  if (orphaned.length) {
    const ids = new Set(orphaned.map((file) => file.id));
    appState.files = appState.files.filter((file) => !ids.has(file.id));
  }
  if (activeAgentId === agentId) resetWorkspace("Agent deleted");
  agentDetailId = "";
  saveWorkspaceState();
  renderRecents();
  if (currentLocalView === "agents") renderLocalView("agents");
  await Promise.allSettled(orphaned.map((file) => apiJson(`/api/files/${encodeURIComponent(file.id)}`, { method: "DELETE" })));
  showToast("Agent deleted");
}

