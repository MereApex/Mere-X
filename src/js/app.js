const GENERATED_IMAGE_PATTERN = /!\[[^\]]*\]\((\/api\/assets\/[^)\s]+)\)/g;

function generatedImageUrls(text) {
  return [...String(text || "").matchAll(GENERATED_IMAGE_PATTERN)].map((match) => match[1]);
}

function rememberGeneratedImages(conversation, message) {
  if (!conversation || !message) return false;
  const urls = generatedImageUrls(message.text);
  if (!urls.length) return false;
  const messageIndex = conversation.messages.findIndex((item) => item.id === message.id);
  const promptMessage = conversation.messages.slice(0, messageIndex).reverse().find((item) => item.role === "user");
  const prompt = String(promptMessage?.text || "Generated image").trim().slice(0, 320) || "Generated image";
  const knownUrls = new Set(appState.images.map((image) => image.url));
  let changed = false;

  for (const url of urls) {
    if (knownUrls.has(url)) continue;
    appState.images.unshift({
      id: makeId("image"),
      url,
      prompt,
      createdAt: message.createdAt || new Date().toISOString(),
      conversationId: conversation.id,
      messageId: message.id
    });
    knownUrls.add(url);
    changed = true;
  }
  return changed;
}

