conversationFeed.addEventListener("click", (event) => {
  const trigger = event.target.closest("[data-message-action]");
  if (!trigger) return;
  const action = trigger.dataset.messageAction;

  if (action === "copy-code") {
    const block = trigger.closest(".code-block");
    copyText(block?.querySelector("pre")?.innerText ?? "", "Code copied");
    const label = trigger.querySelector("span");
    if (label) {
      trigger.classList.add("copied");
      label.textContent = "Copied";
      setTimeout(() => {
        trigger.classList.remove("copied");
        label.textContent = "Copy";
      }, 1600);
    }
    return;
  }

  if (action === "expand-image") {
    openImageViewer(trigger.closest(".chat-image")?.querySelector("img"));
    return;
  }

  const context = messageFromEvent(trigger);
  if (!context) return;
  const { article, conversation, index, message } = context;

  if (action === "retry") {
    article.remove();
    requestReply(conversation);
    return;
  }

  if (currentReply()) return showToast("Wait for the current response to finish");

  if (action === "copy") {
    copyText(message.text, "Message copied");
    return;
  }

  if (action === "speak") {
    speakMessage(message, article);
    return;
  }

  if (action === "regenerate") {
    conversation.messages.splice(index);
    saveWorkspaceState();
    renderConversation(conversation);
    requestReply(conversation);
    return;
  }

  if (action === "edit") {
    promptInput.value = message.text;
    conversation.messages.splice(index);
    saveWorkspaceState();
    renderConversation(conversation);
    renderRecents();
    syncComposer();
    promptInput.focus();
  }
});

