function renderRecents() {
  const all = appState.conversations
    .filter((item) => !item.archived && !item.transient && !item.projectId)
    .sort((a, b) => new Date(b.updatedAt) - new Date(a.updatedAt));
  recentEmpty.hidden = all.length > 0;

  const pinned = all.filter((item) => item.pinned);
  const conversations = all.filter((item) => !item.pinned).slice(0, 20);

  const groups = pinned.length ? [{ label: "Pinned", items: pinned }] : [];
  for (const conversation of conversations) {
    const label = recentGroupOf(conversation.updatedAt);
    const group = groups.at(-1);
    if (group?.label === label && label !== "Pinned") group.items.push(conversation);
    else groups.push({ label, items: [conversation] });
  }

  recentList.innerHTML = groups.map((group) =>
    `<div class="recent-group"><span class="recent-group-label">${group.label}</span>` +
    group.items.map(recentRow).join("") + "</div>"
  ).join("");

  syncDocumentTitle();
}

/* The first exchange is enough to name the conversation properly; the raw first
   message stays as the placeholder until the real title comes back. */
async function nameConversation(conversation) {
  if (conversation.autoTitled || conversation.transient) return;
  conversation.autoTitled = true;
  try {
    const result = await apiJson("/api/title", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        messages: conversation.messages.slice(0, 4).map((item) => ({ role: item.role, text: item.text }))
      })
    });
    const title = String(result?.title || "").trim();
    if (!title) return;
    conversation.title = title;
    saveWorkspaceState();
    renderRecents();
    if (workspaceMode) renderWorkspace();
    if (currentConversationId === conversation.id) conversationCanvas.setAttribute("aria-label", title);
  } catch {
    /* A failed rename is not worth a toast: the placeholder title still reads. */
  }
}

