/* Image work arrives in one piece at the very end, so "Thinking" would sit
   still for a minute. This holds a frame the size of the picture to come and
   eases a count towards it — never to 100 until the file is actually here.
   The count is read from the clock, so it survives leaving the conversation. */
function startImageProgress(article) {
  const startedAt = performance.now();
  let timer = 0;
  let card = null;
  let rail = null;
  let value = null;
  let shown = 0;
  let complete = false;

  const tick = () => {
    const seconds = (performance.now() - startedAt) / 1000;
    shown = Math.max(shown, Math.round(93 * (1 - Math.exp(-seconds / 9))));
    if (!value) return;
    value.textContent = `${shown}%`;
    rail.style.width = `${shown}%`;
  };

  const paint = (host) => {
    host.classList.add("is-thinking");
    const body = host.querySelector(".chat-message-body");
    body.innerHTML =
      '<figure class="image-progress" role="status" aria-label="Creating image">' +
      '<div class="image-progress-stage">' +
      '<span class="image-progress-orbit" aria-hidden="true"></span>' +
      '<span class="image-progress-rail"><i></i></span></div>' +
      '<figcaption class="image-progress-caption">' +
      '<span class="thinking-label">Creating image</span>' +
      '<span class="image-progress-value">0%</span></figcaption></figure>';

    card = body.querySelector(".image-progress");
    rail = body.querySelector(".image-progress-rail i");
    value = body.querySelector(".image-progress-value");

    clearInterval(timer);
    if (complete) {
      value.textContent = "100%";
      rail.style.width = "100%";
      card.classList.add("is-complete");
      return;
    }
    tick();
    timer = setInterval(tick, 110);
  };

  paint(article);

  return {
    detach() {
      clearInterval(timer);
      timer = 0;
      card = rail = value = null;
    },
    adopt(host) {
      paint(host);
    },
    cancel() {
      clearInterval(timer);
      timer = 0;
    },
    /* Let the count land on 100 and the frame settle before the swap. */
    finish() {
      clearInterval(timer);
      timer = 0;
      complete = true;
      if (!value) return Promise.resolve();
      value.textContent = "100%";
      rail.style.width = "100%";
      card.classList.add("is-complete");
      return new Promise((resolve) => setTimeout(resolve, 320));
    }
  };
}

// Derive a sane download extension. Data URLs and asset paths without a
// suffix would otherwise leave the whole string glued onto the filename.
function imageExtension(src) {
  const path = String(src).split(/[?#]/)[0];
  const name = path.slice(path.lastIndexOf("/") + 1);
  const dot = name.lastIndexOf(".");
  const ext = dot > -1 ? name.slice(dot + 1).toLowerCase() : "";
  return /^(png|jpe?g|webp|gif|avif)$/.test(ext) ? ext : "png";
}

