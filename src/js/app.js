async function uploadWorkspaceFiles(files, attachToComposer) {
  if (!workspaceActionAllowed("upload files")) return;
  const withinLimit = files.filter((file) => file.size <= 25 * 1024 * 1024);
  if (withinLimit.length !== files.length) showToast("Each file must be 25 MB or smaller");
  const blocked = settingValue("file-scanning", true) ? withinLimit.filter((file) => fileRisk(file)) : [];
  const blockedIds = new Set(blocked);
  const accepted = withinLimit.filter((file) => !blockedIds.has(file));
  if (blocked.length) {
    const reason = fileRisk(blocked[0]);
    pushNotification("Risky file blocked", `${blocked[0].name}: ${reason}.`, { type: "file_blocked" });
    showToast(`${blocked.length} risky file${blocked.length === 1 ? "" : "s"} blocked`);
  }
  if (!accepted.length) return;

  uploadingFiles += accepted.length;
  renderComposerFiles();
  const form = new FormData();
  accepted.forEach((file) => form.append("files", file, file.name));

  try {
    const result = await apiJson("/api/files", { method: "POST", body: form });
    const uploaded = Array.isArray(result?.files) ? result.files : [];
    const known = new Set(appState.files.map((file) => file.id));
    uploaded.forEach((file) => {
      if (!known.has(file.id)) appState.files.unshift({ ...file, addedAt: new Date().toISOString() });
    });
    if (attachToComposer) {
      const pendingIds = new Set(pendingAttachments.map((file) => file.id));
      pendingAttachments.push(...uploaded.filter((file) => !pendingIds.has(file.id)));
      setTool("File analysis");
    }
    const project = appState.projects.find((item) => item.id === projectFileTarget);
    if (project) {
      const held = new Set((project.files || []).map((file) => file.id));
      project.files = [...uploaded.filter((file) => !held.has(file.id)), ...(project.files || [])];
      touchProject(project);
    }
    const agent = appState.agents.find((item) => item.id === agentFileTarget);
    if (agent) {
      const held = new Set((agent.files || []).map((file) => file.id));
      agent.files = [...uploaded.filter((file) => !held.has(file.id)), ...(agent.files || [])];
      touchAgent(agent);
    }
    recordActivity("files_uploaded", { count: uploaded.length, names: uploaded.map((file) => file.name).slice(0, 8) });
    saveWorkspaceState();
    showToast(`${uploaded.length} file${uploaded.length === 1 ? "" : "s"} ready for Mere X`);
  } catch (error) {
    showToast(error.message);
  } finally {
    uploadingFiles -= accepted.length;
    projectFileTarget = "";
    agentFileTarget = "";
    renderComposerFiles();
    if (currentLocalView === "storage") renderLocalView("storage");
    if (workspaceMode) renderWorkspace();
    if (currentLocalView === "agents") renderLocalView("agents");
  }
}

function saveConversationMessage(text, role = "user", attachments = []) {
  let conversation = appState.conversations.find((item) => item.id === currentConversationId);
  if (!conversation) {
    conversation = {
      id: makeId("chat"),
      title: text.replace(/\s+/g, " ").slice(0, 54),
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      archived: false,
      projectId: workspaceMode ? appState.workspaceProject : "",
      agentId: !workspaceMode ? activeAgentId : "",
      transient: !settingValue("chat-history", true),
      messages: []
    };
    currentConversationId = conversation.id;
    appState.conversations.unshift(conversation);
  }
  const message = { id: makeId("message"), role, text, attachments, createdAt: new Date().toISOString() };
  conversation.messages.push(message);
  conversation.updatedAt = new Date().toISOString();
  if (!conversation.transient) saveWorkspaceState();
  renderRecents();
  return { conversation, message };
}

