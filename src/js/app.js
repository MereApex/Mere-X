function editProjectNote(project, note = null) {
  openActionModal({
    eyebrow: "PROJECT NOTES",
    title: note ? "Edit note" : "New note",
    content: `<label class="action-field"><span>Title</span><input name="title" required maxlength="80" value="${escapeHtml(note?.title || "")}" placeholder="Decision, rule, or reference" /></label>` +
      `<label class="action-field"><span>Note</span><textarea name="content" rows="7" maxlength="6000" placeholder="What should Mere X remember while working in this project?">${escapeHtml(note?.content || "")}</textarea></label>`,
    submitLabel: note ? "Save note" : "Add note",
    onSubmit: (data) => {
      const title = String(data.get("title") || "").trim();
      const content = String(data.get("content") || "").trim();
      if (!title || !content) return false;
      if (note) Object.assign(note, { title, content });
      else {
        project.notes = project.notes || [];
        project.notes.unshift({ id: makeId("note"), title, content, createdAt: new Date().toISOString() });
      }
      touchProject(project);
      saveWorkspaceState();
      renderWorkspace();
      showToast(note ? "Note updated" : "Note added");
    }
  });
}

function organizeConversation(conversation) {
  if (!conversation) return;
  const choices = '<option value="">No project</option>' + appState.projects.map((project) =>
    `<option value="${escapeHtml(project.id)}"${conversation.projectId === project.id ? " selected" : ""}>${escapeHtml(project.name)}</option>`
  ).join("");
  openActionModal({
    eyebrow: "CHAT",
    title: "Organize chat",
    content: `<label class="action-field"><span>Project</span><select name="projectId">${choices}</select><small>Moving a chat gives it the destination project's instructions and shared sources.</small></label>` +
      `<label class="action-check"><input type="checkbox" name="pinned"${conversation.pinned ? " checked" : ""} /><span><strong>Pin this chat</strong><small>Keep it above the other chats in its section.</small></span></label>` +
      `<label class="action-check"><input type="checkbox" name="archived"${conversation.archived ? " checked" : ""} /><span><strong>Archive this chat</strong><small>Hide it without deleting its history.</small></span></label>`,
    submitLabel: "Save",
    onSubmit: (data) => {
      const previousProject = appState.projects.find((project) => project.id === conversation.projectId);
      const projectId = String(data.get("projectId") || "");
      const nextProject = appState.projects.find((project) => project.id === projectId);
      conversation.projectId = nextProject?.id || "";
      if (nextProject) conversation.agentId = "";
      conversation.pinned = data.has("pinned");
      conversation.archived = data.has("archived");
      conversation.updatedAt = new Date().toISOString();
      touchProject(previousProject);
      touchProject(nextProject);
      saveWorkspaceState();
      renderRecents();
      if (workspaceMode) renderWorkspace();
      if (currentLocalView === "archive" || currentLocalView === "projects") renderLocalView(currentLocalView);

      if (currentConversationId === conversation.id) {
        if (conversation.archived) {
          if (nextProject) {
            if (!workspaceMode) setWorkspaceMode(true);
            openProject(nextProject.id, "chats");
          } else resetWorkspace("Conversation archived");
        } else openConversation(conversation.id);
      }
      showToast(nextProject ? `Chat moved to ${nextProject.name}` : "Chat organization updated");
    }
  });
}

async function deleteProjectRecord(projectId) {
  const project = appState.projects.find((item) => item.id === projectId);
  if (!project) return;
  const projectChats = appState.conversations.filter((item) => item.projectId === projectId);
  projectChats.forEach((chat) => stopReply(chat.id));
  appState.projects = appState.projects.filter((item) => item.id !== projectId);
  appState.conversations = appState.conversations.filter((item) => item.projectId !== projectId);
  appState.automations.forEach((item) => { if (item.projectId === projectId) item.projectId = ""; });

  const remainingFileIds = new Set([
    ...appState.projects.flatMap((item) => (item.files || []).map((file) => file.id)),
    ...appState.agents.flatMap((item) => (item.files || []).map((file) => file.id)),
    ...appState.conversations.flatMap((chat) => (chat.messages || []).flatMap((message) => (message.attachments || []).map((file) => file.id)))
  ]);
  const orphaned = (project.files || []).filter((file) => file?.remote === true && !remainingFileIds.has(file.id));
  if (orphaned.length) {
    const orphanedIds = new Set(orphaned.map((file) => file.id));
    appState.files = appState.files.filter((file) => !orphanedIds.has(file.id));
  }

  if (appState.workspaceProject === projectId) closeProject();
  saveWorkspaceState();
  renderRecents();
  if (currentLocalView === "projects") renderLocalView("projects");
  await Promise.allSettled(orphaned.map((file) => apiJson(`/api/files/${encodeURIComponent(file.id)}`, { method: "DELETE" })));
  showToast("Project deleted");
}

/* --- Wiring -------------------------------------------------------------- */

function handleProjectAction(action, trigger) {
  if (action === "new") {
    editProject(null, (created) => openProject(created.id));
    return;
  }
  if (action === "close") return closeProject();

  const project = openProjectRecord();
  if (!project) return;

  if (action === "edit") return editProject(project, () => renderWorkspace());
  if (action === "pin") {
    project.pinned = !project.pinned;
    touchProject(project);
    saveWorkspaceState();
    renderWorkspace();
    showToast(project.pinned ? "Project pinned" : "Project unpinned");
    return;
  }
  if (action === "plugins") return chooseProjectPlugins(project);
  if (action === "new-chat") return startProjectChat();
  if (action === "new-note") return editProjectNote(project);
  if (action === "organize-chat") return organizeConversation(appState.conversations.find((item) => item.id === trigger.dataset.id));
  if (action === "archive-chats") {
    const chats = projectConversations(project);
    if (!chats.length) return showToast("There are no active chats to archive");
    return confirmAction("Archive project chats", `Archive all ${chats.length} active chats in ${project.name}? You can restore them later.`, "Archive chats", () => {
      chats.forEach((chat) => { chat.archived = true; });
      touchProject(project);
      clearConversationSurface();
      projectTab = "chats";
      saveWorkspaceState();
      renderWorkspace();
      renderRecents();
      showToast("Project chats archived");
    });
  }

  if (action === "edit-note") {
    const note = (project.notes || []).find((item) => item.id === trigger.dataset.id);
    if (note) editProjectNote(project, note);
    return;
  }

  if (action === "delete-note") {
    project.notes = (project.notes || []).filter((item) => item.id !== trigger.dataset.id);
    touchProject(project);
    saveWorkspaceState();
    renderWorkspace();
    return;
  }

  if (action === "add-file") {
    projectFileTarget = project.id;
    workspaceFileInput.click();
    return;
  }

  if (action === "remove-file") {
    project.files = (project.files || []).filter((item) => item.id !== trigger.dataset.id);
    touchProject(project);
    saveWorkspaceState();
    renderWorkspace();
  }
}

