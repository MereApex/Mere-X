/* Everything the workspace has attached, handed to the reply source. */
function replyContext(conversation = currentConversation(), overrides = {}) {
  const agent = conversation
    ? (conversation.agentId ? appState.agents.find((item) => item.id === conversation.agentId && item.enabled !== false) : null)
    : (!workspaceMode ? activeAgentRecord(null) : null);
  const project = agent ? null : (conversation
    ? (conversation.projectId ? appState.projects.find((item) => item.id === conversation.projectId) : null)
    : (workspaceMode ? openProjectRecord() : null));
  const notes = (agent?.notes || project?.notes || []).map((note) => ({ title: note.title, content: note.content }));
  const includeWorkspaceContext = agent
    ? agent.memoryMode === "workspace"
    : (!project || project.memoryMode === "workspace");
  const historyBelongsHere = (item) => {
    if (agent) return agent.memoryMode === "workspace" ? !item.projectId : item.agentId === agent.id;
    if (!project) return !item.projectId && !item.agentId;
    if (project.memoryMode === "workspace") return true;
    return item.projectId === project.id;
  };
  const history = settingValue("reference-history", true)
    ? appState.conversations
      .filter((item) => item.id !== conversation?.id && !item.transient && !item.archived && item.messages?.length && historyBelongsHere(item))
      .sort((a, b) => new Date(b.updatedAt) - new Date(a.updatedAt))
      .slice(0, 6)
      .map((item) => ({
        title: `Recent conversation: ${item.title}`,
        content: item.messages.slice(-6).map((message) => `${message.role === "assistant" ? "Mere X" : "User"}: ${String(message.text || "").slice(0, 900)}`).join("\n")
      }))
    : [];
  const scopedPlugins = ((agent?.plugins || project?.plugins) || []).map((id) => pluginCatalogById.get(id)).filter(Boolean);
  return {
    effort: selectedMode,
    model: selectedModel,
    tool: activeTool.hidden ? (agent?.defaultTool || "") : activeToolText.textContent,
    agent: agent ? {
      id: agent.id,
      name: agent.name,
      description: agent.description,
      instructions: agent.instructions,
      capabilities: agent.capabilities,
      defaultTool: agent.defaultTool,
      memoryMode: agent.memoryMode
    } : null,
    project: project ? { id: project.id, name: project.name, description: project.description, instructions: project.instructions || "", memoryMode: project.memoryMode || "project-only" } : null,
    projectFiles: (project?.files || []).filter((file) => file?.remote === true),
    agentFiles: (agent?.files || []).filter((file) => file?.remote === true),
    plugins: scopedPlugins.map((plugin) => ({ id: plugin.id, name: plugin.name })),
    instructions: appState.customInstructions,
    memory: settingValue("memory", true),
    responseStyle: settingValue("response-style", "Balanced"),
    language: settingValue("language", "English"),
    sensitiveContent: settingValue("sensitive-content", "Standard"),
    parentalControls: settingValue("parental-controls", false),
    contentRestrictions: settingValue("content-restrictions", "Standard"),
    sources: [...notes, ...(includeWorkspaceContext ? appState.knowledge.map((item) => ({ title: item.title, content: item.content })) : [])],
    knowledge: history,
    userId: currentUser?.id || "anonymous",
    ...overrides
  };
}

function stopReply(conversationId = currentConversationId) {
  replyFor(conversationId)?.controller.abort();
}

async function requestReply(conversation) {
  stopReply(conversation.id);
  let libraryChanged = false;
  const startedAt = Date.now();
  let completion = null;
  const usedTools = [];

  const message = { id: makeId("message"), role: "assistant", text: "", artifacts: [], createdAt: new Date().toISOString() };
  conversation.messages.push(message);

  const context = replyContext(conversation);
  const article = renderMessage(message);
  article.classList.add("is-streaming");
  const imageProgress = context.tool === "Images" ? startImageProgress(article) : null;
  if (!imageProgress) setThinking(article, true);
  settleFeedAtBottom(true);

  const controller = new AbortController();
  const reply = { controller, article, message, conversation, imageProgress };
  activeReplies.set(conversation.id, reply);
  syncComposerBusy();
  renderRecents();

  /* Every measurement and repaint below is for the screen, and this reply may
     have none: the conversation it belongs to can be off screen the whole time. */
  const onScreen = () => Boolean(reply.article?.isConnected);
  const nearBottom = () => onScreen() && feedIsNearBottom();

  try {
    const history = conversation.messages
      .filter((item) => item.id !== message.id)
      .map((item) => ({ role: item.role, text: item.text, attachments: item.attachments || [] }));

    for await (const piece of streamAssistantReply({
      messages: history,
      context,
      signal: controller.signal,
      onEvent: (event) => {
        if (event.type === "done") completion = event;
        if (event.type === "tool" && event.tool) usedTools.push(event.tool);
        if (event.type === "artifact") {
          const [artifact] = normalizeGeneratedArtifacts([event.artifact]);
          if (artifact && !message.artifacts.some((item) => item.url === artifact.url)) {
            message.artifacts.push(artifact);
            if (reply.article) paintAssistantBody(reply.article, message.text, message.artifacts);
          }
        }
      }
    })) {
      if (imageProgress) {
        message.text += piece;
        continue;
      }
      if (!message.text && reply.article) setThinking(reply.article, false);
      message.text += piece;
      scheduleReplyPaint(reply);
    }

    if (!message.text.trim() && !message.artifacts.length) throw new AssistantError("The response came back empty.");
    if (imageProgress) {
      await imageProgress.finish();
      if (reply.article) setThinking(reply.article, false);
    }
    const wasAtBottom = nearBottom();
    cancelReplyPaint();
    if (reply.article) paintAssistantBody(reply.article, message.text, message.artifacts);
    else showToast(`Reply ready in “${conversation.title}”`);
    if (imageProgress) libraryChanged = rememberGeneratedImages(conversation, message);
    message.model = completion?.model || `Mere X ${context.effort}`;
    message.usage = completion?.usage || null;
    conversation.lastMode = context.effort;
    conversation.lastTool = context.tool;
    recordActivity("assistant_completed", {
      conversationId: conversation.id,
      title: conversation.title,
      agentId: conversation.agentId || "",
      mode: context.effort,
      tool: context.tool,
      tools: [...new Set(usedTools)],
      usage: completion?.usage || null,
      durationMs: Date.now() - startedAt
    });
    const taskIsNotable = new Set(["Deep research", "Web search", "Data analysis", "Images"]).has(context.tool) || Date.now() - startedAt >= 10_000;
    if (settingValue("task-notifications", true) && taskIsNotable) {
      pushNotification("Mere X task completed", `${conversation.title}${context.tool ? ` · ${context.tool}` : ""}`, { type: "task_completed", conversationId: conversation.id });
    } else if (settingValue("sound-notifications", false)) playInterfaceTone();
    if (!conversation.autoTitled) nameConversation(conversation);
    maybeIssueUsageAlerts();
    settleFeedAtBottom(wasAtBottom);
  } catch (error) {
    const wasAtBottom = nearBottom();
    cancelReplyPaint();
    imageProgress?.cancel();

    if (controller.signal.aborted) {
      if (reply.article) setThinking(reply.article, false);
      if (message.text.trim()) {
        message.stopped = true;
        if (reply.article) {
          paintAssistantBody(reply.article, message.text, message.artifacts);
          reply.article.classList.add("is-stopped");
        }
      } else {
        conversation.messages = conversation.messages.filter((item) => item.id !== message.id);
        reply.article?.remove();
      }
    } else {
      conversation.messages = conversation.messages.filter((item) => item.id !== message.id);
      const detail = error instanceof AssistantError ? error.message : "Something went wrong reaching the model.";
      recordActivity("assistant_failed", { conversationId: conversation.id, title: conversation.title, mode: context.effort, tool: context.tool, error: detail, durationMs: Date.now() - startedAt });
      if (reply.article) showReplyError(reply.article, detail);
      else showToast(`Reply failed in “${conversation.title}”`);
    }
    settleFeedAtBottom(wasAtBottom);
  } finally {
    const wasAtBottom = nearBottom();
    imageProgress?.cancel();
    reply.article?.classList.remove("is-streaming");
    activeReplies.delete(conversation.id);
    syncComposerBusy();
    renderRecents();
    conversation.updatedAt = new Date().toISOString();
    if (libraryChanged || !conversation.transient) saveWorkspaceState();
    settleFeedAtBottom(wasAtBottom);
  }
}

