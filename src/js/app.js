function browserDictationFallback() {
  const Recognition = window.SpeechRecognition || window.webkitSpeechRecognition;
  if (!Recognition) return showToast("Microphone transcription is not supported in this browser");
  const recognition = new Recognition();
  recognition.continuous = false;
  recognition.interimResults = false;
  const language = settingValue("voice-language", "Auto-detect");
  if (LANGUAGES[language]) recognition.lang = LANGUAGES[language];
  recognition.addEventListener("start", () => { isListening = true; composerForm.classList.add("is-listening"); });
  recognition.addEventListener("result", (event) => {
    const transcript = [...event.results].map((result) => result[0].transcript).join("").trim();
    promptInput.value += `${promptInput.value && transcript ? " " : ""}${transcript}`;
    syncComposer();
  });
  recognition.addEventListener("end", () => { isListening = false; composerForm.classList.remove("is-listening"); });
  recognition.start();
}

async function startDictation() {
  if (!workspaceActionAllowed("start dictation")) return;
  if (isListening) return stopDictation();
  if (realtimeVoice) stopRealtimeVoice(false);
  if (!navigator.mediaDevices?.getUserMedia || !window.MediaRecorder) return browserDictationFallback();

  try {
    dictationStream = await navigator.mediaDevices.getUserMedia({ audio: { echoCancellation: true, noiseSuppression: true } });
    const preferred = ["audio/webm;codecs=opus", "audio/webm", "audio/mp4"].find((type) => MediaRecorder.isTypeSupported(type));
    dictationChunks = [];
    dictationRecorder = new MediaRecorder(dictationStream, preferred ? { mimeType: preferred } : undefined);
    dictationRecorder.addEventListener("dataavailable", (event) => { if (event.data.size) dictationChunks.push(event.data); });
    dictationRecorder.addEventListener("stop", async () => {
      const mimeType = dictationRecorder?.mimeType || preferred || "audio/webm";
      dictationStream?.getTracks().forEach((track) => track.stop());
      dictationStream = null;
      isListening = false;
      composerForm.classList.remove("is-listening");
      if (!dictationChunks.length) return;
      const extension = mimeType.includes("mp4") ? "m4a" : "webm";
      const form = new FormData();
      form.append("audio", new Blob(dictationChunks, { type: mimeType }), `dictation.${extension}`);
      showToast("Mere X is transcribing…");
      try {
        const result = await apiJson("/api/transcribe", { method: "POST", body: form });
        const transcript = String(result?.text || "").trim();
        promptInput.value += `${promptInput.value && transcript ? " " : ""}${transcript}`;
        syncComposer();
        promptInput.focus();
      } catch (error) {
        showToast(error.message);
      }
    }, { once: true });
    dictationRecorder.start();
    isListening = true;
    composerForm.classList.add("is-listening");
    showToast("Recording… click the microphone again to transcribe");
  } catch (error) {
    dictationStream?.getTracks().forEach((track) => track.stop());
    dictationStream = null;
    showToast(error.name === "NotAllowedError" ? "Microphone permission was denied" : "The microphone could not start");
  }
}

