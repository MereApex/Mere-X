/* Brand marks sit bare on the card. The variants keep single-colour dark marks
   readable once the workspace switches to the dark theme. */
function pluginLogo(plugin, extraClass = "") {
  const light = pluginLogoUrl(plugin.id);
  const dark = plugin.dark ? pluginLogoUrl(`${plugin.id}-dark`) : "";
  const modifier = `${extraClass ? ` ${extraClass}` : ""}${dark ? " has-dark" : ""}${plugin.invertOnDark ? " invert-dark" : ""}${plugin.liftOnDark ? " lift-dark" : ""}`;
  if (!light) return `<span class="plugin-logo${extraClass ? ` ${extraClass}` : ""}"></span>`;
  return `<span class="plugin-logo${modifier}">` +
    `<img class="logo-light" src="${light}" alt="" loading="lazy" />` +
    (dark ? `<img class="logo-dark" src="${dark}" alt="" loading="lazy" />` : "") +
    "</span>";
}

