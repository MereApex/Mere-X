/* Repaint at most once per frame: a token-by-token markdown re-render is wasted
   work between paints. A reply with no article is off screen and paints nothing. */
function scheduleReplyPaint(reply) {
  if (paintHandle || !reply.article?.isConnected) return;
  paintHandle = requestAnimationFrame(() => {
    paintHandle = 0;
    if (!reply.article?.isConnected) return;
    const wasAtBottom = feedIsNearBottom();
    paintAssistantBody(reply.article, reply.message.text, reply.message.artifacts);
    keepFeedAnchored(wasAtBottom);
  });
}

function cancelReplyPaint() {
  if (!paintHandle) return;
  cancelAnimationFrame(paintHandle);
  paintHandle = 0;
}

