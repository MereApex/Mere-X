function normalizeGeneratedArtifacts(value) {
  if (!Array.isArray(value)) return [];
  return value.slice(0, 8).flatMap((artifact) => {
    const url = String(artifact?.url || "");
    const match = url.match(GENERATED_DOCUMENT_URL);
    if (!match) return [];
    const extension = match[1].toLowerCase();
    const fallbackName = `Mere X document.${extension}`;
    const name = String(artifact?.name || fallbackName).replace(/[\\/\u0000-\u001f]/g, "_").slice(0, 160) || fallbackName;
    const size = Number(artifact?.size || 0);
    return [{
      id: String(artifact?.id || url.split("/").pop().split(".")[0]),
      name,
      url,
      size: Number.isFinite(size) && size > 0 ? size : 0,
      type: GENERATED_DOCUMENT_TYPES[extension],
      format: extension.toUpperCase()
    }];
  });
}

