function resolvedTheme(preference) {
  return preference === "system" ? (systemThemeQuery.matches ? "dark" : "cream") : preference;
}

function applyTheme(preference, persist = true) {
  const normalizedPreference = ["cream", "dark", "system"].includes(preference) ? preference : "cream";
  const resolved = resolvedTheme(normalizedPreference);
  themePreference = normalizedPreference;
  document.documentElement.dataset.theme = resolved;
  document.documentElement.dataset.themePreference = normalizedPreference;
  document.querySelector('meta[name="theme-color"]')?.setAttribute("content", resolved === "dark" ? "#121310" : "#fbf8f1");
  if (persist) {
    try { localStorage.setItem(THEME_STORAGE_KEY, normalizedPreference); } catch (error) { /* storage can be unavailable */ }
  }
}

