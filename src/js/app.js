/* A conversation owns its reply, not the workspace: leaving for another chat
   detaches the stream from the screen but never stops it, and coming back
   adopts it again mid-flight. */
const activeReplies = new Map();
let paintHandle = 0;

function replyFor(conversationId) {
  return (conversationId && activeReplies.get(conversationId)) || null;
}

function currentReply() {
  return replyFor(currentConversationId);
}

/* The conversation is going off screen: drop the DOM it was painting into. */
function leaveConversation() {
  const reply = currentReply();
  if (!reply) return;
  reply.article = null;
  reply.imageProgress?.detach();
}

/* Back on screen after a fresh render: hand the stream its new article. */
function attachRunningReply(conversation) {
  const reply = replyFor(conversation.id);
  if (!reply) return;
  const article = conversationFeed.querySelector(`[data-message-id="${reply.message.id}"]`);
  if (!article) return;
  reply.article = article;
  article.classList.add("is-streaming");
  if (reply.imageProgress) reply.imageProgress.adopt(article);
  else if (!reply.message.text) setThinking(article, true);
}

function feedIsNearBottom() {
  return conversationFeed.scrollHeight - conversationFeed.scrollTop - conversationFeed.clientHeight < 140;
}

function keepFeedAnchored(wasAtBottom) {
  if (wasAtBottom) conversationFeed.scrollTop = conversationFeed.scrollHeight;
}

/* Finishing a response reveals message actions and can change the final layout
   after the last stream paint. Re-anchor once now and once after layout settles. */
function settleFeedAtBottom(wasAtBottom) {
  if (!wasAtBottom) return;
  keepFeedAnchored(true);
  requestAnimationFrame(() => keepFeedAnchored(true));
}

