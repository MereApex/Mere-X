/* Clears the conversation surface without touching a reply that is still
   running: it keeps streaming into the conversation it belongs to. */
function clearConversationSurface() {
  leaveConversation();
  currentConversationId = null;
  conversationFeed.replaceChildren();
  conversationCanvas.classList.remove("has-conversation");
  syncComposerBusy();
}

function setWorkspaceMode(on) {
  if (workspaceMode === on) {
    /* Already on this side: the switcher still walks you back out of a
       full-page view like Plugins or Library. */
    if (currentLocalView !== "chat") {
      showChatSurface();
      renderWorkspace();
    }
    return;
  }

  /* Each side keeps its own conversation: switching never drags a plain chat
     into a project, or a project's work back into plain chat. */
  leaveConversation();
  if (on) {
    activeAgentId = "";
    lastChatConversationId = currentConversationId;
    currentConversationId = null;
  } else {
    currentConversationId = lastChatConversationId;
  }
  workspaceMode = on;

  workspaceSwitcher.querySelectorAll("[data-workspace]").forEach((option) => {
    const selected = option.dataset.workspace === (on ? "work" : "chat");
    option.classList.toggle("active", selected);
    option.setAttribute("aria-selected", String(selected));
  });

  showChatSurface();
  const conversation = currentConversation();
  if (conversation) {
    renderConversation(conversation);
    conversationCanvas.classList.add("has-conversation");
  } else {
    conversationFeed.replaceChildren();
    conversationCanvas.classList.remove("has-conversation");
  }

  $(".welcome-block h1").innerHTML = on
    ? "What will we <em>build</em> today?"
    : "Where should we <em>begin</em>?";
  $(".welcome-copy").textContent = on
    ? "Plan, create, and organize ambitious work with Mere X."
    : "One workspace for ideas, research, creation, and complex work.";

  promptInput.value = "";
  syncComposer();
  syncComposerBusy();
  renderWorkspace();
  renderAgentSurface();
  renderRecents();
}

