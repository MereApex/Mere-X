/* What the server says about every plugin Mere X can genuinely connect to:
   whether it has OAuth credentials, and whose account is linked. */
let pluginStatus = new Map();

async function refreshPluginStatus() {
  try {
    const result = await apiJson("/api/plugins");
    pluginStatus = new Map((result?.plugins || []).map((plugin) => [plugin.id, plugin]));
    const connected = [...pluginStatus.values()].filter((plugin) => plugin.connected).map((plugin) => plugin.id);
    const changed = connected.length !== appState.plugins.length
      || connected.some((id) => !appState.plugins.includes(id));
    if (changed) {
      appState.plugins = connected;
      appState.projects.forEach((project) => {
        project.plugins = (project.plugins || []).filter((id) => connected.includes(id));
      });
      appState.agents.forEach((agent) => {
        agent.plugins = (agent.plugins || []).filter((id) => connected.includes(id));
      });
      appState.workspacePlugins = appState.workspacePlugins.filter((id) => connected.includes(id));
      saveWorkspaceState();
      if (workspaceMode) renderWorkspace();
    }
    return true;
  } catch {
    return false;
  }
}

