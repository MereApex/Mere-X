/* Links leave the workspace safely, and every fenced block gets its own copy. */
function decorateMessageBody(body) {
  body.querySelectorAll("a[href]").forEach((link) => {
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });
  body.querySelectorAll("table").forEach((table) => {
    if (table.parentElement?.classList.contains("table-scroll")) return;
    const scroller = document.createElement("div");
    scroller.className = "table-scroll";
    table.replaceWith(scroller);
    scroller.append(table);
  });
  body.querySelectorAll("img").forEach((image) => {
    if (image.closest(".chat-image")) return;
    const figure = document.createElement("figure");
    figure.className = "chat-image";
    image.replaceWith(figure);
    figure.append(image);
    figure.insertAdjacentHTML("beforeend",
      '<button type="button" class="chat-image-open" data-message-action="expand-image" aria-label="Open image full size">' +
      '<span><svg><use href="#i-arrow-ne"></use></svg></span></button>');
  });
  body.querySelectorAll("pre").forEach((pre) => {
    const language = pre.querySelector("code")?.className.match(/language-([\w+#-]+)/)?.[1] ?? "";
    const wrapper = document.createElement("div");
    wrapper.className = "code-block";
    pre.replaceWith(wrapper);
    wrapper.innerHTML = `<div class="code-head"><span class="code-lang">${escapeHtml(language || "code")}</span>` +
      `<button type="button" class="code-copy" data-message-action="copy-code">` +
      `<svg><use href="#i-copy"></use></svg><span>Copy</span></button></div>`;
    wrapper.append(pre);
  });
}

